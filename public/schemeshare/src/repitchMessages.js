/**
 * Replaces placeholders ([Name], [Article], [Signature]) in the template with lead & employee information,
 * with full multi-lingual regional translation and bilingual capabilities.
 */
export function formatRepitchMessage(templateOrMsg, lead, employee, lang = 'en', isBilingual = false) {
  if (!templateOrMsg) return '';

  let templateText = '';
  let englishFallbackText = '';
  let msgId = null;

  if (typeof templateOrMsg === 'object' && templateOrMsg !== null) {
    msgId = templateOrMsg.id;
    const trans = getRepitchMessageTranslation(msgId, lang, templateOrMsg);
    templateText = trans.text || templateOrMsg.template || '';
    const enTrans = getRepitchMessageTranslation(msgId, 'en', templateOrMsg);
    englishFallbackText = enTrans.text || templateOrMsg.template || '';
  } else if (typeof templateOrMsg === 'string') {
    templateText = templateOrMsg;
  }

  const customerName = (lead?.customerName || 'Customer').trim();
  const articleNumber = (lead?.articleNumber || 'ARTICLE_NO').trim();
  const signature = buildRepitchSignature(employee, lang);

  let formatted = templateText;

  // Replace [Name]
  formatted = formatted.replace(/\[Name\]/g, customerName);

  // Replace ([Article]) or [Article]
  formatted = formatted.replace(/\(\[Article\]\)/g, `(${articleNumber})`);
  formatted = formatted.replace(/\[Article\]/g, articleNumber);

  // Replace [Signature]
  formatted = formatted.replace(/\[Signature\]/g, signature);

  // If bilingual mode requested and language is not English, append English block
  if (isBilingual && lang !== 'en' && englishFallbackText) {
    let enFormatted = englishFallbackText;
    enFormatted = enFormatted.replace(/\[Name\]/g, customerName);
    enFormatted = enFormatted.replace(/\(\[Article\]\)/g, `(${articleNumber})`);
    enFormatted = enFormatted.replace(/\[Article\]/g, articleNumber);
    enFormatted = enFormatted.replace(/\[Signature\]/g, ''); // no duplicate signature

    formatted = `${formatted}\n\n--------------------\n*Official English Summary:*\n${enFormatted.trim()}`;
  }

  return formatted;
}

/**
 * Gets sorted categories prioritizing the lead's associated schemes
 */
export function getCategoriesForLead(lead) {
  const leadSchemes = lead?.schemes || [];
  
  // Clone categories
  const categories = JSON.parse(JSON.stringify(REPITCH_CATEGORIES));

  // Determine priority
  return categories.map(cat => {
    // Check if lead schemes match this category id or shortname
    const isDirectMatch = leadSchemes.some(sId => {
      if (sId === cat.id) return true;
      if (cat.id === 'ppf_nsc' && (sId === 'ppf' || sId === 'nsc')) return true;
      if (cat.id === 'sb' && (sId === 'sb' || sId === 'ippb')) return true;
      if (cat.id === 'pli' && (sId === 'pli' || sId === 'rpli')) return true;
      return false;
    });

    return {
      ...cat,
      isLeadMatch: isDirectMatch
    };
  }).sort((a, b) => {
    if (a.isLeadMatch && !b.isLeadMatch) return -1;
    if (!a.isLeadMatch && b.isLeadMatch) return 1;
    return 0;
  });
}

