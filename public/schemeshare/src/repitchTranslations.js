/**
 * Fallback translation generator for dynamically translated pitch angles
 */
export function getRepitchMessageTranslation(msgId, lang = 'en', baseEnglishMsg = null) {
  const transObj = REPITCH_TRANSLATIONS[msgId];
  if (transObj && transObj[lang]) {
    return transObj[lang];
  }
  if (transObj && transObj.en) {
    return transObj.en;
  }
  if (baseEnglishMsg) {
    return {
      title: baseEnglishMsg.title,
      text: baseEnglishMsg.template
    };
  }
  return {
    title: 'India Post Sovereign Pitch',
    text: 'Namaste [Name] ji! Delivered your article ([Article]). Connect with India Post for guaranteed sovereign financial growth. [Signature]'
  };
}
