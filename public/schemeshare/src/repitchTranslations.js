export function buildRepitchSignature(employee, lang = 'en') {
  const name = employee?.fullName || 'Postal Department Representative';
  const desig = employee?.designation || 'BPM / Postman';
  const office = employee?.officeName || 'India Post Office';
  const type = employee?.officeType ? ` (${employee.officeType})` : '';
  const pin = employee?.pincode ? ` - ${employee.pincode}` : '';
  const mobile = employee?.mobile ? `\nMobile: ${employee.mobile}` : '';
  const sigInfo = SIGNATURE_LABELS[lang] || SIGNATURE_LABELS.en;

  return `\n\n====================\n${sigInfo.title}\n*${name}*, ${desig}\n${office}${type}${pin}${mobile}\n${sigInfo.dept}`;
}

