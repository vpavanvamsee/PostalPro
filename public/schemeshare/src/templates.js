/**
 * Generate a high-converting, sovereign-backed, bilingual WhatsApp message.
 * Strictly uses standard ASCII/universal typographical characters with no emojis
 * to ensure 100% compatibility on all WhatsApp mobile clients and feature phones.
 */
export function generateWhatsAppPitch({
  addresseeName,
  secondaryName,
  articleNumber,
  selectedSchemeIds,
  language = 'te',
  employee
}) {
  const cleanName = (addresseeName || 'Respected Customer').trim();
  const careOf = secondaryName ? ` (C/o ${secondaryName.trim()})` : '';
  const article = (articleNumber || '').trim().toUpperCase();

  // Clean, official greetings without emojis
  const greetings = {
    te: `నమస్తే ${cleanName} గారు${careOf}!\nఈరోజు మీ ఇండియా పోస్ట్ ఆర్టికల్ (${article}) ను విజయవంతంగా డెలివరీ చేశాము.`,
    hi: `नमस्ते ${cleanName} जी${careOf}!\nआज आपका इंडिया पोस्ट आर्टिकल (${article}) सफलतापूर्वक डिलीवर किया गया।`,
    en: `Namaste ${cleanName}${careOf}!\nDelivered your India Post article (${article}) successfully today.`,
    ta: `வணக்கம் ${cleanName}${careOf}!\nஉங்கள் இந்தியா போஸ்ட் தபால் (${article}) இன்று வெற்றிகரமாக டெலிவரி செய்யப்பட்டது.`,
    kn: `ನಮಸ್ಕಾರ ${cleanName}${careOf}!\nನಿಮ್ಮ ಇಂಡಿಯಾ ಪೋಸ್ಟ್ ಪಾರ್ಸೆಲ್/ಪತ್ರ (${article}) ಇಂದು ಯಶಸ್ವಿಯಾಗಿ ತಲುಪಿಸಲಾಗಿದೆ.`
  };

  const primaryGreeting = greetings[language] || greetings['en'];
  const englishGreeting = language !== 'en' 
    ? `Namaste ${cleanName}${careOf}!\nDelivered your India Post article (${article}) successfully today.`
    : '';

  // Scheme blocks
  const validSchemeIds = selectedSchemeIds.length > 0 ? selectedSchemeIds : ['ssy'];
  
  const regionalSections = [];
  const englishSections = [];

  validSchemeIds.forEach(id => {
    const data = TEMPLATE_CONTENT[id];
    const schemeMeta = SCHEMES.find(s => s.id === id);
    const schemeHeader = schemeMeta ? schemeMeta.name : id.toUpperCase();
    if (!data) return;

    const reg = data[language] || data['en'];
    regionalSections.push(
      `*${schemeHeader}*\n${reg.hook}\n\n*Key Highlights:*\n${reg.features}\n\n${reg.scenario}`
    );

    if (language !== 'en') {
      const eng = data['en'];
      englishSections.push(
        `*${schemeHeader}*\n${eng.hook}\n\n*Key Highlights:*\n${eng.features}\n\n${eng.scenario}`
      );
    }
  });

  const regionalBody = regionalSections.join('\n\n---\n\n');
  const englishBody = englishSections.length > 0 ? englishSections.join('\n\n---\n\n') : '';

  // Clean Call to Actions without emojis
  const ctaRegional = {
    te: "డోర్‌స్టెప్ సేవలు, ఖాతా వివరాలు లేదా వడ్డీ లెక్కల కోసం *YES* అని రిప్లై ఇవ్వండి.",
    hi: "घर बैठे खाता खोलने, ब्याज कैलकुलेशन या अधिक जानकारी के लिए *YES* लिखकर रिप्लाई करें।",
    en: "Reply *YES* for a doorstep consultation or interest calculation.",
    ta: "கூடுதல் விவரங்கள் மற்றும் வீட்டிலேயே சேவைகளைப் பெற *YES* என்று பதிலளிக்கவும்.",
    kn: "ಹೆಚ್ಚಿನ ಮಾಹಿತಿ ಅಥವಾ ಮನೆ ಬಾಗಿಲ ಸೇವೆಗಾಗಿ *YES* ಎಂದು ರಿಪ್ಲೈ ಮಾಡಿ."
  }[language] || "Reply *YES* for a doorstep consultation or interest calculation.";

  let message = `${primaryGreeting}\n\n---\n\n${regionalBody}\n\n*Next Step:* ${ctaRegional}`;

  if (language !== 'en' && englishBody) {
    message += `\n\n====================\n*Official India Post Information (English):*\n${englishGreeting}\n\n${englishBody}\n\n*Next Step:* Reply *YES* for a doorstep consultation or interest calculation.`;
  }

  // Verified Sign-off
  const empName = employee?.fullName || 'Postal Department Representative';
  const empDesig = employee?.designation || 'BPM / Postman';
  const empOffice = employee?.officeName || 'India Post Office';
  const empType = employee?.officeType || 'BO';
  const empPin = employee?.pincode ? ` - ${employee.pincode}` : '';
  const empMobile = employee?.mobile ? `\nMobile: ${employee.mobile}` : '';

  message += `\n\n====================\n*Official Postal Communication*\n*${empName}*, ${empDesig}\n${empOffice} (${empType})${empPin}${empMobile}\n_India Post • Department of Posts_`;

  return message;
}
